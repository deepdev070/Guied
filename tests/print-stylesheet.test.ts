import { describe, it } from "node:test";
import assert from "node:assert";
import fs from "node:fs";
import path from "node:path";
import { siteConfig } from "../src/lib/site.ts";

describe("Prompt 63: Print Stylesheet & Printable Checklist View", () => {
  it("verifies globals.css contains complete @media print styles", () => {
    const cssPath = path.join(process.cwd(), "src/app/globals.css");
    const cssContent = fs.readFileSync(cssPath, "utf-8");

    assert.ok(cssContent.includes("@media print"), "globals.css must define @media print");
    assert.ok(cssContent.includes("header"), "Print media must target header");
    assert.ok(cssContent.includes("footer"), "Print media must target footer");
    assert.ok(cssContent.includes(".ad-slot"), "Print media must hide .ad-slot");
    assert.ok(
      cssContent.includes("attr(href)"),
      "Print media must render official URLs with attr(href)"
    );
    assert.ok(
      cssContent.includes("break-inside: avoid"),
      "Print media must prevent awkward section page cuts"
    );
  });

  it("verifies Header, Footer, and Ads have print:hidden utility class", () => {
    const headerPath = path.join(process.cwd(), "src/components/layout/Header.tsx");
    const footerPath = path.join(process.cwd(), "src/components/layout/Footer.tsx");
    const leaderboardPath = path.join(process.cwd(), "src/components/ads/LeaderboardAd.tsx");
    const sidebarAdPath = path.join(process.cwd(), "src/components/ads/SidebarAd.tsx");

    assert.ok(
      fs.readFileSync(headerPath, "utf-8").includes("print:hidden"),
      "Header must have print:hidden"
    );
    assert.ok(
      fs.readFileSync(footerPath, "utf-8").includes("print:hidden"),
      "Footer must have print:hidden"
    );
    assert.ok(
      fs.readFileSync(leaderboardPath, "utf-8").includes("print:hidden"),
      "Leaderboard ad must have print:hidden"
    );
    assert.ok(
      fs.readFileSync(sidebarAdPath, "utf-8").includes("print:hidden"),
      "Sidebar ad must have print:hidden"
    );
  });

  it("verifies PrintTaskView source code implements all required prompt specifications", () => {
    const printViewPath = path.join(process.cwd(), "src/components/task/PrintTaskView.tsx");
    const printViewContent = fs.readFileSync(printViewPath, "utf-8");

    // 1. Title & State & Date Generated
    assert.ok(printViewContent.includes("State / UT:"), "Must render state label in print header");
    assert.ok(
      printViewContent.includes("Date generated:"),
      "Must render 'Date generated:' in print header"
    );

    // 2. Checklist with empty boxes
    assert.ok(
      printViewContent.includes('data-testid="print-empty-box"'),
      "Must render empty checkbox box for pen ticking"
    );
    assert.ok(
      printViewContent.includes("border-2 border-black"),
      "Checkbox box must have crisp print border"
    );

    // 3. Compact fees & steps
    assert.ok(
      printViewContent.includes("Total Mandatory Statutory Fee"),
      "Must calculate and display compact mandatory fees"
    );
    assert.ok(
      printViewContent.includes("Procedure Steps (Compact Overview)"),
      "Must display compact procedure steps"
    );

    // 4. Official links as full URLs
    assert.ok(
      printViewContent.includes("{link.url}"),
      "Must print full destination URL for official government portals"
    );

    // 5. Required footer text
    const requiredFooter = "Generated by {siteConfig.name} - verify on official portal";
    assert.ok(
      printViewContent.includes(requiredFooter),
      "Must render exact footer: 'Generated by <site> - verify on official portal'"
    );
    assert.strictEqual(
      siteConfig.name,
      "India Paperwork Guide",
      "Site name must be India Paperwork Guide"
    );
  });

  it("verifies TaskPageView and Sidebar integrate print controls", () => {
    const pageViewPath = path.join(process.cwd(), "src/components/task/TaskPageView.tsx");
    const sidebarPath = path.join(process.cwd(), "src/components/task/TaskSidebar.tsx");
    const docSectionPath = path.join(process.cwd(), "src/components/task/DocumentSection.tsx");

    const pageViewContent = fs.readFileSync(pageViewPath, "utf-8");
    const sidebarContent = fs.readFileSync(sidebarPath, "utf-8");
    const docSectionContent = fs.readFileSync(docSectionPath, "utf-8");

    assert.ok(pageViewContent.includes("<PrintTaskView"), "TaskPageView must render PrintTaskView");
    assert.ok(
      sidebarContent.includes("window.print()"),
      "TaskSidebar must provide print button calling window.print()"
    );
    assert.ok(
      docSectionContent.includes("window.print()"),
      "DocumentSection must provide print button calling window.print()"
    );
  });
});
